const yearGroups = {};

for (const date in archive) {
    const year = "20" + date.slice(0, 2);

    if (!yearGroups[year]) {
        const yearItem = document.createElement("li");
        yearItem.classList.add("yearGroup");
        
        const yearText = document.createElement("span");
        yearText.classList.add("year");
        
        const yearImg = document.createElement("img");
        yearImg.src = "img/year.svg";
        yearImg.alt = year;
        
        const yearLabel = document.createElement("span");
        yearLabel.classList.add("yearLabel");
        yearLabel.innerText = year;
        
        yearText.appendChild(yearImg);
        yearText.appendChild(yearLabel);
        
        const dateList = document.createElement("ul");

        dateList.classList.add("yearDates");

        yearItem.appendChild(yearText);
        yearItem.appendChild(dateList);
        topicList.appendChild(yearItem);

        yearGroups[year] = {
            item: yearItem,
            list: dateList
        };

        // 연도 클릭
        yearText.addEventListener("click", (e) => {
            e.stopPropagation();
            yearItem.classList.toggle("open");
        });

    }

    // 날짜
    const dateItem = document.createElement("li");
    dateItem.classList.add("dateItem");
    dateItem.dataset.theme = date;
    const dateSpan = document.createElement("span");

    dateSpan.classList.add("date");
    const month = date.slice(2, 4);
    const day = date.slice(4, 6);
    dateSpan.innerText = `${month}${day}`;

    // 주제
    const topicSpan = document.createElement("span");
    topicSpan.classList.add("topic");
    topicSpan.innerText = archive[date].topic;
    dateItem.appendChild(dateSpan);
    dateItem.appendChild(topicSpan);
    yearGroups[year].list.appendChild(dateItem);
}

