//==========================//
// 날짜 위치 계산
//==========================//

function getTargetScrollTop(
    container,
    target
) {

    if (!target) {
        return 0;
    }


    const containerRect =
        container.getBoundingClientRect();


    const targetRect =
        target.getBoundingClientRect();


    const currentScroll =
        container.scrollTop;


    const targetY =
        currentScroll +
        (
            targetRect.top -
            containerRect.top
        ) -
        140;


    const maxScroll =
        container.scrollHeight -
        container.clientHeight;


    return Math.max(
        0,
        Math.min(
            targetY,
            maxScroll
        )
    );

}


