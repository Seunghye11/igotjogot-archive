function makeColumn(member, container) {

    for (const theme in archive) {

        archive[theme][member].forEach(work => {

            const workBox =
                document.createElement("div");

            workBox.classList.add("work");

            workBox.dataset.theme = theme;


            // 이미지
            const img =
                document.createElement("img");

            img.src = work.img;
            img.draggable = false;


            // 설명
            const desc =
                document.createElement("div");

            desc.classList.add("desc");

            desc.innerHTML = `
                <h4>${work.title}</h4>
                <p>${work.description}</p>
            `;


            workBox.appendChild(img);
            workBox.appendChild(desc);

            container.appendChild(workBox);

        });

    }

}


//==========================//
// 무한 반복용 Track 생성
//==========================//
//
// 각 칼럼:
//
// [1세트]
// [2세트]
// [3세트]
//
// 작품들을 하나의 Track 안에 넣는다.
//

function createLoopTrack(container) {

    const originalWorks =
        Array.from(
            container.querySelectorAll(".work")
        );


    // 2세트
    originalWorks.forEach(work => {

        const clone =
            work.cloneNode(true);

        container.appendChild(clone);

    });


    // 3세트
    originalWorks.forEach(work => {

        const clone =
            work.cloneNode(true);

        container.appendChild(clone);

    });


    // Track 생성
    const track =
        document.createElement("div");

    track.classList.add("scrollTrack");


    // 현재 container에 있는 작품 전부 이동
    const allWorks =
        Array.from(
            container.querySelectorAll(".work")
        );


    allWorks.forEach(work => {

        track.appendChild(work);

    });


    container.appendChild(track);


    return track;

}


